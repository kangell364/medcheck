#!/usr/bin/env node
/**
 * Concatenate the Phase 2 migrations into one file for the Supabase SQL editor.
 *
 * The Supabase CLI (`supabase db push`) is the better route because it records
 * which migrations have run. This file exists for the case where the CLI is not
 * installed and somebody is pasting SQL into a browser: eight separate pastes
 * in the right order is eight chances to get the order wrong, and these
 * migrations are NOT idempotent -- re-running one fails on an existing type or
 * table.
 *
 * The seeds are deliberately NOT included. They carry `on conflict do nothing`
 * and are safe to re-run, so they are applied separately and re-applied
 * whenever content changes. Bundling them here would tempt somebody to paste
 * the whole thing twice.
 *
 *   node scripts/build-deploy-sql.mjs
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join } from 'node:path'

// --check writes nothing and fails if the generated file is out of date. A
// generated file that has silently drifted from its source is worse than no
// generated file: somebody pastes it into production believing it matches the
// migrations, and it does not.
const CHECK_ONLY = process.argv.includes('--check')

const ROOT = join(dirname(new URL(import.meta.url).pathname), '..')
const MIGRATIONS = join(ROOT, 'supabase', 'migrations')
const OUT = join(ROOT, 'supabase', 'deploy', 'phase-2-schema.sql')
const STEPS = join(ROOT, 'supabase', 'deploy', 'steps')
const PREFIX = '20260201'

const files = readdirSync(MIGRATIONS)
  .filter((f) => f.startsWith(PREFIX) && f.endsWith('.sql'))
  .sort()

if (files.length === 0) {
  console.error(`No migrations matching ${PREFIX}* in ${MIGRATIONS}`)
  process.exit(1)
}

const parts = [
  `-- Texas Exam Prep — Phase 2 schema`,
  `--`,
  `-- Generated by scripts/build-deploy-sql.mjs. Do not edit by hand; edit the`,
  `-- migrations in supabase/migrations/ and regenerate.`,
  `--`,
  `-- Run this ONCE against a project that already has the Phase 1 schema.`,
  `-- These statements are not idempotent: running them twice fails on an`,
  `-- existing type or table, which is the correct behaviour, not a bug.`,
  `--`,
  `-- Wrapped in a single transaction, so a failure anywhere leaves the`,
  `-- database exactly as it was rather than half-migrated.`,
  ...files.map((f) => `--   - ${f}`),
  ``,
  `begin;`,
  ``,
]

for (const file of files) {
  parts.push(
    `-- ${'-'.repeat(74)}`,
    `-- ${file}`,
    `-- ${'-'.repeat(74)}`,
    ``,
    readFileSync(join(MIGRATIONS, file), 'utf8').trim(),
    ``,
  )
}

parts.push(`commit;`, ``)

// The same migrations again, one file each, every one wrapped in its own
// transaction.
//
// Why both shapes exist: the single file is one paste and one transaction,
// which is what you want when it works. When it does NOT work, a 970-line
// paste into a browser SQL editor is the hardest possible thing to diagnose --
// a truncated paste and a broken statement look identical, and the error
// points at a line that reads fine in the repository. Eight small files
// cannot truncate the same way, and whichever one fails names the migration.
//
// Each step is its own transaction, so a failure leaves that step's database
// exactly as it was. The steps must still be run IN ORDER; a later one
// references what an earlier one created.
function buildSteps() {
  return files.map((file, index) => {
    const n = String(index + 1).padStart(2, '0')
    const name = file.replace(/^\d+_/, '').replace(/\.sql$/, '')
    const body = [
      `-- Texas Exam Prep — Phase 2, step ${index + 1} of ${files.length}`,
      `--`,
      `-- ${file}`,
      `--`,
      `-- Generated by scripts/build-deploy-sql.mjs. Do not edit by hand.`,
      `--`,
      `-- Run the steps IN ORDER. This one is a single transaction, so if it`,
      `-- fails nothing in it is applied and you can fix the cause and re-run`,
      `-- this step alone. Steps already applied must NOT be re-run: they are`,
      `-- not idempotent and will fail on an existing type or table.`,
      ``,
      `begin;`,
      ``,
      readFileSync(join(MIGRATIONS, file), 'utf8').trim(),
      ``,
      `commit;`,
      ``,
    ].join('\n')
    return { path: join(STEPS, `${n}-${name}.sql`), body }
  })
}

const steps = buildSteps()

const generated = parts.join('\n')
const relative = OUT.slice(ROOT.length + 1)

if (CHECK_ONLY) {
  if (!existsSync(OUT)) {
    console.error(`${relative} is missing. Run: node scripts/build-deploy-sql.mjs`)
    process.exit(1)
  }
  if (readFileSync(OUT, 'utf8') !== generated) {
    console.error(
      `${relative} is out of date with supabase/migrations/.\n` +
        `Run: node scripts/build-deploy-sql.mjs`,
    )
    process.exit(1)
  }
  for (const step of steps) {
    const rel = step.path.slice(ROOT.length + 1)
    if (!existsSync(step.path) || readFileSync(step.path, 'utf8') !== step.body) {
      console.error(
        `${rel} is missing or out of date.\n` +
          `Run: node scripts/build-deploy-sql.mjs`,
      )
      process.exit(1)
    }
  }
  console.log(
    `${relative} and ${steps.length} step file(s): up to date`,
  )
} else {
  writeFileSync(OUT, generated)
  mkdirSync(STEPS, { recursive: true })
  for (const step of steps) writeFileSync(step.path, step.body)
  console.log(
    `${relative}: ${files.length} migration(s), ${generated.split('\n').length} lines`,
  )
  console.log(`supabase/deploy/steps/: ${steps.length} step file(s)`)
}
